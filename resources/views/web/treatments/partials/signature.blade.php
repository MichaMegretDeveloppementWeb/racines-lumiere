            <div>
                <h3>Une rencontre</h3>
                <p>Aucun de nos rituels n'est écrit à l'avance. Chacun commence par une rencontre&nbsp;: nous prenons le temps de vous écouter, de comprendre ce que vous traversez et ce dont vous avez besoin aujourd'hui. Le bol d'air Jacquier et le bain de pieds préparent ensuite votre corps et votre esprit à recevoir le soin.</p>
            </div>
            <div>
                <h3>Votre rituel</h3>
                <p>Puis votre rituel prend forme, composé pour vous le jour même. Un massage pour délier le corps, un soin du visage pour révéler l'éclat de la peau, des huiles essentielles choisies pour vous, un voyage dans les couleurs, les outils de sonothérapie, ou d'autres plus holistiques quand ils ont du sens. Le fil qui relie tout cela, c'est notre intuition, nourrie par nos années d'expérience et par ce que vous nous confiez.</p>
            </div>
            <div>
                <h3>Un temps ensemble</h3>
                <p>Le rituel se referme comme il a commencé, par un temps ensemble. Autour d'une tisane, nous revenons doucement sur ce que votre corps a exprimé et sur ce que vous avez ressenti, pour vous laisser repartir avec quelques clés et le temps de laisser le soin se poser en vous.</p>
            </div>
        </div>
